import argparse
import sys
import os
import datetime
import re
from pathlib import Path

from preprocessor import Preprocessor
from parser import Parser
from utils import dump_tokens_to_file
from isa import add_picowizard_opcodes

def write_header(output: Path, binary):
    object_name = output.stem

    # Format binary as hex
    hex_bytes = ", ".join(f"0x{b:02X}" for b in binary)

    # Header generation
    date_str = datetime.datetime.now().strftime("%Y-%m-%d")

    header_contents = f"""// Generated by Picowiazrd Infrastructure Assembler on {date_str} from {output.name}

#pragma once

#include <stdint.h>

const uint8_t {object_name}[] ALIGN(32) = {{
    {hex_bytes}
}};
"""

    output.write_text(header_contents)

def parse_isa_version(isa: str) -> tuple[int, bool]:
    match = re.fullmatch(r"(\d+)\.(\d+)(P)?", isa, re.IGNORECASE)

    if not match:
        raise ValueError(f"Invalid ISA version: {isa!r}")

    major, minor, plus = match.groups()
    version = int(major) * 100 + int(minor) * 10

    return version, plus is not None

def main():
    parser = argparse.ArgumentParser(description="Picowizard Infastructure Assembler")
    parser.add_argument("input", type=Path, help="Input .s assembly source file")
    parser.add_argument("-o", "--output", type=Path, help="Output binary file", default="out.bin")
    parser.add_argument("-t", "--tokens", type=Path, help="Dump tokens after preprocessor to file for debugging.")
    parser.add_argument("-bt", "--backtrace", help="Enable python backtrace on errors.", action="store_true")
    parser.add_argument("-c", "--cheader", help="Output C header instead of binary file.", action="store_true")
    parser.add_argument("--isa", help="Select ISA Version")
    
    include_directories = [Path(__file__).resolve().parent / "include"]

    args = parser.parse_args()

    input_source = args.input
    output_binary = args.output

    # Construct ISA
    isa_version_string = "1.2"
    if args.isa:
        isa_version_string = args.isa

    isa_version, isa_plus = parse_isa_version(str(isa_version_string))
    add_picowizard_opcodes(isa_plus)

    try:
        preprocessor = Preprocessor(include_directories)

        # Add definitions
        preprocessor.add_definition("PICOWIZARD_ISA_VERSION", isa_version)
        if isa_plus:
            preprocessor.add_definition("PICOWIZARD_ISA_PLUS")

        # Recursive include
        tokens = preprocessor.recursive_include(input_source)

        # Take on all the macros
        tokens = preprocessor.gather(tokens)

        # Do not allow circular definitions
        preprocessor.check_circular_definitions()

        # Evaluate
        tokens = preprocessor.run(tokens)
    except Exception as e:
        # If backtrace, send this off to the top
        if args.backtrace:
            raise e

        print(f"{os.path.basename(input_source)}: Preprocessor Failed")
        print(f"\t{e}")
        sys.exit(1)

    # Dump them if asked
    if args.tokens:
        dump_tokens_to_file(tokens, args.tokens)

    try:
        # Generate program
        parser = Parser()
        program = parser.run(tokens)
    except Exception as e:
        # If backtrace, send this off to the top
        if args.backtrace:
            raise e

        print(f"{os.path.basename(input_source)}: Parser Failed")
        print(f"\t{e}")
        sys.exit(1)
    
    try:

        # Create bytecode
        bytecode, _ = program.generate_bytecode()

        if args.cheader:
            write_header(output_binary, bytecode)
        else:
            # Write to file
            with open(output_binary, "wb") as f:
                f.write(bytecode)   
    except Exception as e:
        # If backtrace, send this off to the top
        if args.backtrace:
            raise e

        print(f"{os.path.basename(input_source)}: Bytecode Generation Failed")
        print(f"\t{e}")
        sys.exit(1)


if __name__ == "__main__":
    main()